BEGIN;
CREATE TABLE staking_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network VARCHAR(80) NOT NULL,
    genesis_root VARCHAR(66) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('RUNNING', 'OBSERVED', 'INCOMPLETE')),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    checkpoint_observed_at TIMESTAMP WITH TIME ZONE,
    state_root VARCHAR(66),
    client_version VARCHAR(250),
    error_code VARCHAR(80),
    validator_json TEXT,
    raw_evidence TEXT
);
CREATE INDEX idx_staking_network_started ON staking_observations(network, started_at);
COMMIT;
